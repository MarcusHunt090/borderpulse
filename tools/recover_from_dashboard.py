"""
recover_from_dashboard.py — rebuild BorderPulse's data/ and validation/ folders
from a published dashboard HTML (every payload is embedded as `const X = <json>;`).

Usage:
    python3 recover_from_dashboard.py <published index.html> <repo root>

Writes:
    data/**           every CSV in MANIFEST (from TIDY_CSV / MONTHLY_CSV / DATA.context
                      is not enough — we use the embedded MANIFEST + per-file bundles when
                      present, else fall back to the full payloads)
    validation/*.json the VAL / BENCH / LAB / HOR / LL / INFER / VINTAGE / BT / ONSET payloads
    dashboard_body.html  the page with each payload replaced by its /*__X__*/ placeholder
"""
import json, os, re, sys, hashlib

# JS const name in the page -> placeholder name used by build.py
PAYLOADS = {"DATA": "DATA", "VAL": "VALIDATION", "BENCH": "BENCH", "LAB": "LAB", "HOR": "HORIZONS",
            "LL": "LEADLAG", "INFER": "INFER", "VINTAGE": "VINTAGE", "BT": "BORDERTEST", "ONSET": "ONSET",
            "TIDY_CSV": "TIDY", "MONTHLY_CSV": "MONTHLY", "BRIEF_MD": "BRIEF", "MANIFEST": "MANIFEST",
            "TECHNOTE_MD": "TECHNOTE"}
# the publish step wraps the body fragment in this skeleton; strip it to get dashboard_body.html back
SKELETON_END_OF_HEAD = "</head><body>\n"
SKELETON_TAIL = "\n</body></html>"

def main(html_path, root):
    html = open(html_path, encoding="utf-8").read()
    dec = json.JSONDecoder()
    found = {}
    body = html
    for name, ph in PAYLOADS.items():
        m = re.search(r"const\s+%s\s*=\s*" % re.escape(name), body)
        if not m:
            print("  (not embedded)", name)
            continue
        start = m.end()
        try:
            obj, end = dec.raw_decode(body, start)
        except json.JSONDecodeError as e:
            print("  decode failed for", name, e)
            continue
        found[name] = obj
        body = body[:start] + "/*__%s__*/" % ph + body[end:]
        print("  recovered", name, "->", ph, type(obj).__name__)
    # strip the publish-time document skeleton
    i = body.find(SKELETON_END_OF_HEAD)
    if i >= 0 and body.lstrip().lower().startswith("<!doctype html><html><head>"):
        body = body[i + len(SKELETON_END_OF_HEAD):]
    if body.endswith(SKELETON_TAIL):
        body = body[:-len(SKELETON_TAIL)]
    return found, body

if __name__ == "__main__":
    html_path, root = sys.argv[1], sys.argv[2]
    found, body = main(html_path, root)
    os.makedirs(os.path.join(root, "validation"), exist_ok=True)
    os.makedirs(os.path.join(root, "data"), exist_ok=True)
    with open(os.path.join(root, "dashboard_body.html"), "w", encoding="utf-8") as f:
        f.write(body)
    # validation payloads are re-generated by the pipeline; keep the published copies for reference only
    for k in ["VAL", "BENCH", "LAB", "HOR", "LL", "INFER", "VINTAGE", "BT", "ONSET"]:
        if k in found:
            with open(os.path.join(root, "validation", "published_" + k.lower() + ".json"), "w") as f:
                json.dump(found[k], f, indent=1)
    if "DATA" in found:
        with open(os.path.join(root, "borderpulse_output.json"), "w") as f:
            json.dump(found["DATA"], f, indent=1)
    for k, fn in [("TIDY_CSV", "borderpulse_tidy.csv"), ("MONTHLY_CSV", "borderpulse_monthly.csv"),
                  ("BRIEF_MD", "borderpulse_brief.md"), ("TECHNOTE_MD", "technical_note.md")]:
        if k in found and isinstance(found[k], str):
            with open(os.path.join(root, fn), "w", encoding="utf-8") as f:
                f.write(found[k])
    if "MANIFEST" in found:
        with open(os.path.join(root, "data", "MANIFEST.json"), "w") as f:
            json.dump(found["MANIFEST"], f, indent=1)
    print("done; keys:", sorted(found))
